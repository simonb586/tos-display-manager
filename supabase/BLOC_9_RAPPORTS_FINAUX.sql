create or replace function public.diagnostic_rapports_v09()
returns table(
  communications_total bigint,
  communications_envoyees bigint,
  communications_echec bigint,
  edt_avec_rapport bigint
)
language sql
security definer
set search_path = public
as $$
  select
    (select count(*) from public.communications_finales),
    (select count(*) from public.communications_finales where statut = 'Envoyé'),
    (select count(*) from public.communications_finales where statut = 'Échec'),
    (select count(*) from public.suivi_des_edt where rapport_final_envoye = true);
$$;

grant execute on function public.diagnostic_rapports_v09()
to authenticated;
