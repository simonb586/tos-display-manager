create table if not exists public.requetes_clients (
  id bigint generated by default as identity primary key,
  client text,
  demandeur_nom text,
  demandeur_courriel text,
  type_requete text not null default 'Installation',
  priorite text not null default 'Normale',
  support_id text,
  description text,
  statut text not null default 'Nouvelle',
  bon_de_travail_id bigint,
  converted_at timestamptz,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.edt_phases (
  id bigint generated by default as identity primary key,
  edt_id bigint not null references public.suivi_des_edt(id) on delete cascade,
  nom text not null,
  ordre integer not null default 1,
  statut text not null default 'À faire',
  date_debut_prevue date,
  date_fin_prevue date,
  date_debut_reelle timestamptz,
  date_fin_reelle timestamptz,
  progression integer not null default 0 check (progression between 0 and 100),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.edt_assignments (
  id bigint generated by default as identity primary key,
  edt_id bigint not null references public.suivi_des_edt(id) on delete cascade,
  user_id bigint,
  user_email text not null,
  role_assignment text not null default 'Installateur',
  date_debut date,
  date_fin date,
  statut text not null default 'Assigné',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(edt_id, user_email, role_assignment)
);

create table if not exists public.operations_history (
  id bigint generated by default as identity primary key,
  entity_type text not null,
  entity_id text,
  entity_reference text,
  action text not null,
  old_data jsonb,
  new_data jsonb,
  details text,
  user_id uuid default auth.uid(),
  user_email text,
  created_at timestamptz not null default now()
);

