create or replace function public.tdm_operations_audit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  ref text;
  email_value text;
begin
  select email into email_value from auth.users where id = auth.uid();

  ref := coalesce(
    to_jsonb(new)->>'no_edt',
    to_jsonb(new)->>'no_bt',
    to_jsonb(new)->>'id',
    to_jsonb(old)->>'no_edt',
    to_jsonb(old)->>'no_bt',
    to_jsonb(old)->>'id'
  );

  insert into public.operations_history(
    entity_type,
    entity_id,
    entity_reference,
    action,
    old_data,
    new_data,
    details,
    user_id,
    user_email
  )
  values(
    tg_table_name,
    coalesce(to_jsonb(new)->>'id', to_jsonb(old)->>'id'),
    ref,
    tg_op,
    case when tg_op = 'INSERT' then null else to_jsonb(old) end,
    case when tg_op = 'DELETE' then null else to_jsonb(new) end,
    null,
    auth.uid(),
    email_value
  );

  return coalesce(new, old);
end;
$$;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'suivi_des_edt',
    'bons_de_travail',
    'requetes_clients',
    'edt_phases',
    'edt_assignments'
  ]
  loop
    execute format('drop trigger if exists tdm_operations_audit on public.%I', table_name);
    execute format(
      'create trigger tdm_operations_audit after insert or update or delete on public.%I for each row execute function public.tdm_operations_audit()',
      table_name
    );
  end loop;
end $$;

create or replace function public.refresh_edt_progress(p_edt_id bigint)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  computed integer;
  installed integer;
begin
  select coalesce(round(avg(
    case
      when statut = 'Terminée' then 100
      else coalesce(progression, 0)
    end
  )), 0)::integer,
  count(*) filter (where statut = 'Terminée')
  into computed, installed
  from public.bons_de_travail
  where edt_id = p_edt_id;

  update public.suivi_des_edt
  set
    progression = computed,
    supports_installes = installed,
    updated_at = now()
  where id = p_edt_id;

  return computed;
end;
$$;

create or replace function public.sync_edt_progress_from_work_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.edt_id is not null then
    perform public.refresh_edt_progress(new.edt_id);
  end if;
  if tg_op = 'UPDATE' and old.edt_id is distinct from new.edt_id and old.edt_id is not null then
    perform public.refresh_edt_progress(old.edt_id);
  end if;
  return new;
end;
$$;

drop trigger if exists sync_edt_progress_from_work_order on public.bons_de_travail;
create trigger sync_edt_progress_from_work_order
after insert or update of statut, progression, edt_id
on public.bons_de_travail
for each row execute function public.sync_edt_progress_from_work_order();

create or replace function public.diagnostic_bloc11()
returns table(
  edt_total bigint,
  edt_actifs bigint,
  bt_ouverts bigint,
  requetes_nouvelles bigint,
  assignations_actives bigint
)
language sql
security definer
set search_path = public
as $$
  select
    (select count(*) from public.suivi_des_edt),
    (select count(*) from public.suivi_des_edt where statut not in ('Terminé','Annulé')),
    (select count(*) from public.bons_de_travail where statut not in ('Terminée','Annulée')),
    (select count(*) from public.requetes_clients where statut = 'Nouvelle'),
    (select count(*) from public.edt_assignments where statut <> 'Retiré');
$$;

grant execute on function public.diagnostic_bloc11() to authenticated;
