-- Conversion tolérante des dates historiques stockées en TEXT.
create or replace function public.tdm_try_date(p_value text)
returns date language plpgsql immutable as $$
begin
  if p_value is null or btrim(p_value) = '' then return null; end if;
  begin return p_value::date; exception when others then return null; end;
end;$$;

create table if not exists public.edt_supports (
  id bigint generated by default as identity primary key,
  edt_id bigint not null references public.suivi_des_edt(id) on delete cascade,
  phase_id bigint references public.edt_phases(id) on delete set null,
  support_id text not null references public.infrastructures(support_id) on update cascade on delete restrict,
  statut text not null default 'Planifié',
  priorite text not null default 'Normale',
  assigne_a text,
  date_cible date,
  bon_de_travail_id bigint references public.bons_de_travail(id) on delete set null,
  progression integer not null default 0 check (progression between 0 and 100),
  bloque boolean not null default false,
  motif_blocage text,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (edt_id, support_id)
);

create index if not exists edt_supports_edt_idx on public.edt_supports(edt_id, statut);
create index if not exists edt_supports_phase_idx on public.edt_supports(phase_id, statut);
create index if not exists edt_supports_support_idx on public.edt_supports(support_id);
create index if not exists edt_supports_bt_idx on public.edt_supports(bon_de_travail_id);

alter table public.suivi_des_edt add column if not exists supports_planifies integer default 0;
alter table public.suivi_des_edt add column if not exists supports_en_cours integer default 0;
alter table public.suivi_des_edt add column if not exists supports_bloques integer default 0;
alter table public.suivi_des_edt add column if not exists supports_termines integer default 0;
alter table public.suivi_des_edt add column if not exists derniere_synchro timestamptz;

alter table public.bons_de_travail add column if not exists edt_support_id bigint references public.edt_supports(id) on delete set null;
create unique index if not exists bons_de_travail_edt_support_unique
  on public.bons_de_travail(edt_support_id)
  where edt_support_id is not null;

alter table public.edt_supports enable row level security;

drop policy if exists "edt_supports_read" on public.edt_supports;
