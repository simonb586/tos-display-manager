create or replace function public.refresh_edt_enterprise(p_edt_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total integer := 0;
  v_planifies integer := 0;
  v_en_cours integer := 0;
  v_bloques integer := 0;
  v_termines integer := 0;
  v_progression integer := 0;
  v_phase record;
begin
  select
    count(*)::integer,
    count(*) filter (where statut in ('Planifié','À faire'))::integer,
    count(*) filter (where statut in ('En cours','Démarré'))::integer,
    count(*) filter (where bloque = true or statut = 'Bloqué')::integer,
    count(*) filter (where statut in ('Terminé','Terminée','Complété','Complétée'))::integer,
    coalesce(round(avg(
      case
        when statut in ('Terminé','Terminée','Complété','Complétée') then 100
        else coalesce(progression,0)
      end
    )),0)::integer
  into v_total, v_planifies, v_en_cours, v_bloques, v_termines, v_progression
  from public.edt_supports
  where edt_id = p_edt_id;

  -- Recalcule chaque phase à partir des supports réellement affectés.
  for v_phase in select id from public.edt_phases where edt_id = p_edt_id loop
    update public.edt_phases p
       set progression = coalesce((
             select round(avg(case
               when es.statut in ('Terminé','Terminée','Complété','Complétée') then 100
               else coalesce(es.progression,0)
             end))::integer
             from public.edt_supports es
             where es.phase_id = p.id
           ),0),
           statut = case
             when not exists (select 1 from public.edt_supports es where es.phase_id = p.id) then p.statut
             when not exists (
               select 1 from public.edt_supports es
               where es.phase_id = p.id
                 and es.statut not in ('Terminé','Terminée','Complété','Complétée')
             ) then 'Terminée'
             when exists (
               select 1 from public.edt_supports es
               where es.phase_id = p.id and es.progression > 0
             ) then 'En cours'
             else 'À faire'
           end,
           updated_at = now()
     where p.id = v_phase.id;
  end loop;

  update public.suivi_des_edt
     set supports_prevus = v_total,
         supports_cibles = v_total,
         supports_planifies = v_planifies,
         supports_en_cours = v_en_cours,
         supports_bloques = v_bloques,
         supports_termines = v_termines,
         supports_installes = v_termines,
         supports_completes = v_termines,
         progression = v_progression,
         avancement = v_progression,
         statut = case
           when v_total > 0 and v_termines = v_total then 'Terminé'
           when v_en_cours > 0 or v_termines > 0 then 'En cours'
           else statut
         end,
         date_fin = case when v_total > 0 and v_termines = v_total then coalesce(date_fin, current_date) else date_fin end,
         derniere_synchro = now(),
         updated_at = now()
   where id = p_edt_id;

  return jsonb_build_object(
    'ok', true,
    'edt_id', p_edt_id,
    'supports_total', v_total,
    'planifies', v_planifies,
    'en_cours', v_en_cours,
    'bloques', v_bloques,
    'termines', v_termines,
    'progression', v_progression
  );
end;
$$;

create or replace function public.assigner_supports_edt_v0129(
  p_edt_id bigint,
  p_support_ids text[],
  p_phase_id bigint default null,
  p_priorite text default 'Normale',
  p_assigne_a text default null,
  p_date_cible date default null,
  p_generer_bt boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_edt public.suivi_des_edt%rowtype;
  v_support_id text;
  v_es public.edt_supports%rowtype;
  v_bt_id bigint;
  v_added integer := 0;
  v_skipped integer := 0;
  v_missing text[] := array[]::text[];
begin
  if public.current_app_role() not in ('Administrateur','Coordonnateur') then
    raise exception 'Permission insuffisante.';
  end if;

  select * into v_edt from public.suivi_des_edt where id = p_edt_id for update;
  if not found then raise exception 'EDT introuvable.'; end if;

  if p_phase_id is not null and not exists (
    select 1 from public.edt_phases where id = p_phase_id and edt_id = p_edt_id
  ) then
    raise exception 'La phase ne correspond pas à cet EDT.';
  end if;

  foreach v_support_id in array coalesce(p_support_ids, array[]::text[]) loop
    v_support_id := trim(v_support_id);
    if v_support_id = '' then continue; end if;

    if not exists (select 1 from public.infrastructures where support_id = v_support_id) then
      v_missing := array_append(v_missing, v_support_id);
      continue;
    end if;

    insert into public.edt_supports(
      edt_id, phase_id, support_id, statut, priorite, assigne_a, date_cible, updated_at
    ) values (
      p_edt_id, p_phase_id, v_support_id, 'Planifié', coalesce(p_priorite,'Normale'), p_assigne_a, p_date_cible, now()
    )
    on conflict (edt_id, support_id) do update
      set phase_id = coalesce(excluded.phase_id, edt_supports.phase_id),
          priorite = excluded.priorite,
          assigne_a = coalesce(excluded.assigne_a, edt_supports.assigne_a),
          date_cible = coalesce(excluded.date_cible, edt_supports.date_cible),
          updated_at = now()
    returning * into v_es;

    if p_generer_bt and v_es.bon_de_travail_id is null then
      insert into public.bons_de_travail(
        no_bt, type_bt, support_id, no_edt, edt_id, phase_id, edt_support_id,
        priorite, statut, assigne_a, date_cible, client, description, progression, updated_at
      ) values (
        'BT-' || regexp_replace(coalesce(v_edt.no_edt, p_edt_id::text), '[^A-Za-z0-9]', '', 'g') || '-' || v_support_id,
        'Installation', v_support_id, v_edt.no_edt, p_edt_id, p_phase_id, v_es.id,
        coalesce(p_priorite,'Normale'), 'À faire', p_assigne_a, p_date_cible, v_edt.client,
        'Travaux EDT ' || coalesce(v_edt.no_edt, p_edt_id::text) || ' — support ' || v_support_id,
        0, now()
      )
      on conflict (edt_support_id) where edt_support_id is not null do update
        set phase_id = excluded.phase_id,
            priorite = excluded.priorite,
            assigne_a = coalesce(excluded.assigne_a, bons_de_travail.assigne_a),
            date_cible = coalesce(excluded.date_cible, bons_de_travail.date_cible),
            updated_at = now()
      returning id into v_bt_id;

      update public.edt_supports set bon_de_travail_id = v_bt_id, updated_at = now() where id = v_es.id;
    end if;

    update public.infrastructures
       set prochain_edt_cible = v_edt.no_edt,
           updated_at = now()
     where support_id = v_support_id;

    v_added := v_added + 1;
  end loop;

  perform public.refresh_edt_enterprise(p_edt_id);

  return jsonb_build_object(
    'ok', true,
    'edt_id', p_edt_id,
    'supports_affectes', v_added,
    'supports_ignores', v_skipped,
    'supports_introuvables', to_jsonb(v_missing)
  );
end;
$$;

create or replace function public.retirer_support_edt_v0129(p_edt_id bigint, p_support_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_no_edt text;
  v_bt_id bigint;
begin
  if public.current_app_role() not in ('Administrateur','Coordonnateur') then
    raise exception 'Permission insuffisante.';
  end if;

  select no_edt into v_no_edt from public.suivi_des_edt where id = p_edt_id;
  select bon_de_travail_id into v_bt_id from public.edt_supports where edt_id=p_edt_id and support_id=p_support_id;

  delete from public.edt_supports where edt_id=p_edt_id and support_id=p_support_id;
  if v_bt_id is not null then delete from public.bons_de_travail where id=v_bt_id and statut in ('À faire','Planifié','Annulée'); end if;

  update public.infrastructures
     set prochain_edt_cible = nullif(prochain_edt_cible, v_no_edt), updated_at=now()
   where support_id=p_support_id;

  perform public.refresh_edt_enterprise(p_edt_id);
  return jsonb_build_object('ok',true,'edt_id',p_edt_id,'support_id',p_support_id);
end;
$$;

create or replace function public.sync_edt_support_from_bt_v0129()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.edt_support_id is not null then
    update public.edt_supports
       set statut = case
             when new.statut = 'Terminée' then 'Terminé'
             when new.statut = 'En cours' then 'En cours'
             when new.statut = 'Annulée' then 'Annulé'
             else 'Planifié'
           end,
           progression = case when new.statut='Terminée' then 100 else coalesce(new.progression,0) end,
           assigne_a = coalesce(new.assigne_a, assigne_a),
           date_cible = coalesce(public.tdm_try_date(new.date_cible::text), date_cible),
           completed_at = case when new.statut='Terminée' then coalesce(new.date_fin_reelle,now()) else null end,
           updated_at = now()
     where id = new.edt_support_id;
  end if;
  if new.edt_id is not null then perform public.refresh_edt_enterprise(new.edt_id); end if;
  return new;
end;
$$;

drop trigger if exists sync_edt_support_from_bt_v0129 on public.bons_de_travail;
create trigger sync_edt_support_from_bt_v0129
after insert or update of statut, progression, assigne_a, date_cible, date_fin_reelle
on public.bons_de_travail
for each row execute function public.sync_edt_support_from_bt_v0129();

create or replace function public.sync_bt_from_edt_support_v0129()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.bon_de_travail_id is not null then
    update public.bons_de_travail
       set phase_id = new.phase_id,
           assigne_a = new.assigne_a,
           priorite = new.priorite,
           date_cible = new.date_cible::text,
           progression = new.progression,
           statut = case
             when new.statut in ('Terminé','Terminée','Complété','Complétée') then 'Terminée'
             when new.statut='En cours' then 'En cours'
             when new.statut='Annulé' then 'Annulée'
             else 'À faire'
           end,
           updated_at = now()
     where id = new.bon_de_travail_id;
  end if;
  perform public.refresh_edt_enterprise(new.edt_id);
  return new;
end;
$$;

drop trigger if exists sync_bt_from_edt_support_v0129 on public.edt_supports;
