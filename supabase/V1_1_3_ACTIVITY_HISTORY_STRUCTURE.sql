create or replace function public.resolve_terrain_sync_v113(p_id uuid,p_resolution text)
returns public.terrain_sync_diagnostics language plpgsql security definer set search_path=public as $$
declare result public.terrain_sync_diagnostics;
begin
  if public.current_app_role() not in ('Administrateur','Coordonnateur') then raise exception 'Permission insuffisante.' using errcode='42501'; end if;
  update public.terrain_sync_diagnostics set statut='resolved',resolved_at=now(),resolved_by=auth.uid(),resolution=nullif(trim(p_resolution),'')
  where id=p_id and lower(statut) in ('échec','echec','error','erreur','failed') returning * into result;
  if result.id is null then raise exception 'Diagnostic introuvable ou non résoluble.'; end if;
  return result;
end $$;

create or replace function public.request_terrain_sync_retry_v113(p_id uuid)
returns public.terrain_sync_diagnostics language plpgsql security definer set search_path=public as $$
declare original public.terrain_sync_diagnostics;result public.terrain_sync_diagnostics;
begin
  if public.current_app_role() not in ('Administrateur','Coordonnateur') then raise exception 'Permission insuffisante.' using errcode='42501'; end if;
  select * into original from public.terrain_sync_diagnostics where id=p_id;
  if original.id is null then raise exception 'Diagnostic introuvable.'; end if;
  insert into public.terrain_sync_diagnostics(reference,support_id,visuel_id,utilisateur,etape,statut,details,device_id,operation,campagne_id,edt_id,attempt,last_attempt_at,source)
  values(original.reference,original.support_id,original.visuel_id,(select email from auth.users where id=auth.uid()),'Nouvelle tentative demandée','pending',jsonb_build_object('retry_of',original.id),original.device_id,original.operation,original.campagne_id,original.edt_id,original.attempt+1,now(),'manual_retry_request') returning * into result;
  return result;
end $$;
revoke all on function public.resolve_terrain_sync_v113(uuid,text),public.request_terrain_sync_retry_v113(uuid) from public,anon;
grant execute on function public.resolve_terrain_sync_v113(uuid,text),public.request_terrain_sync_retry_v113(uuid) to authenticated;

